create table if not exists public.gprs_packets (
  id bigint generated by default as identity primary key,
  packet_type text not null check (packet_type in ('STA', 'STB', 'STH')),
  device_id text not null,
  device_time text not null,
  payload text not null,
  alarm_label text,
  created_at timestamptz not null default now()
);

create index if not exists gprs_packets_device_time_idx
  on public.gprs_packets (device_time);

alter table public.gprs_packets enable row level security;

drop policy if exists "Public can read GPRS packets" on public.gprs_packets;
create policy "Public can read GPRS packets"
  on public.gprs_packets for select
  using (true);
