create table if not exists public.logger_readings (
  id bigint generated by default as identity primary key,
  device_id text not null,
  received_at_receiver timestamptz not null default now(),
  remote_peer text,
  payload_text text not null default '',
  payload_base64 text,
  created_at timestamptz not null default now()
);

create index if not exists logger_readings_device_received_idx
  on public.logger_readings (device_id, received_at_receiver desc);

alter table public.logger_readings enable row level security;

-- No anon/authenticated policies are created. Inserts are performed by the Edge Function
-- using the server-side service role key, never from the browser.
